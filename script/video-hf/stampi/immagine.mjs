// Stampo «immagine» (26/10/2026, Marco: «le immagini puoi prenderle dalla mail»): un'immagine o una breve clip grande,
// in una cornice con bordo d'accento, con didascalia e credito sotto. Solo per piani scritti a mano o con file forniti:
// il modello che scrive i piani non ha file da mostrare.
// dati.media è il percorso del file (monta.mjs lo copia in assets/media/); .mp4 diventa un <video> muto, il resto un'<img>.
// La clip sta fuori dal palco (base.mjs, «fuori»): HyperFrames non accetta un <video data-start> dentro un contenitore
// temporizzato. Entra quando la voce nomina la didascalia; prima c'è la barra della scena.
import { C, scena, s3, esc, misura, attacchi, formatoDi } from '../base.mjs';

const MAX_DIDASCALIA = 48, MAX_CREDITO = 44;
const testo = (x) => (typeof x === 'string' ? x.trim() : '');
const nomeFile = (p) => String(p).split(/[\\/]/).pop();

export default {
  nome: 'immagine',
  descrizione: 'ONLY when the plan provides a media file: show a picture or short clip large, with a caption and a credit line below',
  schema: '{ "media": "path of the .mp4/.jpg/.png file", "rapporto": 1.78, "didascalia": "Eastern-style 3D RPG (max 48)", "credito": "Generated by K3.1 Pro · Moonshot AI (max 44)" }',

  valida(dati) {
    const p = [];
    if (!dati || typeof dati !== 'object') return ['dati mancanti'];
    if (typeof dati.media !== 'string' || !/\.(mp4|jpg|jpeg|png|webp)$/i.test(dati.media)) p.push('media deve essere un file .mp4, .jpg, .png o .webp');
    const r = Number(dati.rapporto ?? 16 / 9);
    if (!(r >= 0.5 && r <= 4)) p.push(`rapporto fuori misura (${dati.rapporto})`);
    const di = testo(dati.didascalia), cr = testo(dati.credito);
    if (!di) p.push('didascalia mancante');
    else if (di.length > MAX_DIDASCALIA) p.push(`didascalia troppo lunga (${di.length} > ${MAX_DIDASCALIA})`);
    if (cr.length > MAX_CREDITO) p.push(`credito troppo lungo (${cr.length} > ${MAX_CREDITO})`);
    return p;
  },

  parole(dati) { return attacchi(dati, [['didascalia', testo(dati.didascalia)]]); },

  html({ id, px, dati, durata, t, etichetta, numero, formato = 'orizzontale' }) {
    const { W, fondo, margine: M } = formatoDi(formato);
    const vert = formato === 'verticale';
    const r = Number(dati.rapporto ?? 16 / 9);
    // la cornice più grande che sta fra la barra e la didascalia, col rapporto del file
    const alto = vert ? 230 : 160;
    const spazioTesti = vert ? 260 : 170;
    const maxW = W - 2 * M, maxH = fondo - alto - spazioTesti;
    let w = maxW, h = Math.round(maxW / r);
    if (h > maxH) { h = maxH; w = Math.round(maxH * r); }
    // nello Short la cornice e i testi stanno a metà dello spazio libero (prova del 26/10: in alto restava vuoto sotto)
    const x = Math.round((W - w) / 2), y = vert ? alto + Math.max(0, Math.round((fondo - alto - h - spazioTesti) / 2)) : alto;
    const di = testo(dati.didascalia), cr = testo(dati.credito);
    const fsD = misura(di, { larghezza: maxW, max: vert ? 64 : 56, min: vert ? 40 : 34, fattore: 0.5 });
    const fsC = vert ? (dati.skillTutorial?36:32) : 28;
    const yT = y + h + (vert ? 48 : 34);
    const D = s3(durata);
    const src = `assets/media/${esc(nomeFile(dati.media))}`;
    const video = /\.mp4$/i.test(dati.media);
    const tDi = Math.min(Math.max(0.3, t('didascalia', 0.6)), Math.max(0.3, durata - 1.5));
    const css = `${dati.skillTutorial?`.${px}barra{gap:36px;letter-spacing:.08em}.${px}barra span:first-child{white-space:nowrap;overflow:hidden;text-overflow:ellipsis;max-width:calc(100% - 160px);flex:1}.${px}barra span:last-child{white-space:nowrap;flex:none}`:''}
    #${px}cornice { position: absolute; left: ${x}px; top: ${y}px; width: ${w}px; height: ${h}px; border-radius: 18px; overflow: hidden;
      border: 4px solid ${C.accento}; background: ${C.scuro}; opacity: 0; }
    #${px}cornice video, #${px}cornice img { width: 100%; height: 100%; object-fit: cover; display: block; }
    .${px}testi { position: absolute; left: ${M}px; right: ${M}px; top: ${yT}px; text-align: center; }
    .${px}didascalia { font-size: ${fsD}px; line-height: 1.15; color: ${C.crema}; opacity: 0; }
    .${px}credito { margin-top: 14px; font-family: "JetBrains Mono", monospace; font-size: ${fsC}px; letter-spacing: 0.06em; color: ${C.accento}; opacity: 0; }`;
    const corpo = `<div class="${px}testi"><div class="${px}didascalia" id="${px}didascalia">${esc(di)}</div>${cr ? `<div class="${px}credito" id="${px}credito">${esc(cr)}</div>` : ''}</div>`;
    const media = video
      ? `<video id="${px}clip" class="clip" src="${src}" data-start="0" data-duration="${D}" data-track-index="3" muted playsinline></video>`
      : `<img src="${src}" alt="">`;
    const fuori = `<div id="${px}cornice">${media}</div>`;
    const anima = `
      tl.fromTo(q("#${px}cornice"), { opacity: 0, y: 40 }, { opacity: 1, y: 0, duration: 0.8, ease: "power3.out" }, 0.25);
      tl.fromTo(q("#${px}didascalia"), { opacity: 0, y: 18 }, { opacity: 1, y: 0, duration: 0.6, ease: "power2.out" }, ${s3(tDi)});
      ${cr ? `tl.fromTo(q("#${px}credito"), { opacity: 0 }, { opacity: 1, duration: 0.5, ease: "power1.out" }, ${s3(tDi + 0.3)});` : ''}`;
    return scena({ id, px, durata, etichetta, numero, css, corpo, anima, formato, fuori });
  },
};
